-- SECTION 1: CREATE TABLES
-- ============================================================

-- 1. Judge List
CREATE TABLE JUDGE_LIST (
    JUDGE_ID    VARCHAR(256) PRIMARY KEY,
    JF_NAME     VARCHAR(256),
    JL_NAME     VARCHAR(256),
    JUDGE_EMAIL VARCHAR(256)
);

-- 2. Organizer
CREATE TABLE ORGANIZER (
    ORGANISER_ID   VARCHAR(256) PRIMARY KEY,
    ORGANISER_NAME VARCHAR(256),
    ORGANISER_TYPE VARCHAR(256)
);

-- 3. Sponsor
-- NOTE: Original used Oracle's NUMBER; replaced with NUMERIC for PostgreSQL
CREATE TABLE SPONSER (
    SPONS_ID     VARCHAR(256) PRIMARY KEY,
    SPONS_NAME   VARCHAR(256),
    SPONS_AMOUNT NUMERIC,
    SPONS_TYPE   VARCHAR(256)
);

-- 4. Competition
-- NOTE: Original DDL had a typo referencing ORGANISERS; corrected to ORGANIZER
CREATE TABLE COMPETITION (
    COMP_ID       VARCHAR(256) PRIMARY KEY,
    COMP_DATE     DATE,
    ORGANISER_ID  VARCHAR(256),
    COMP_LOCATION VARCHAR(256),
    COMP_NAME     VARCHAR(256),
    FOREIGN KEY (ORGANISER_ID) REFERENCES ORGANIZER(ORGANISER_ID)
);

-- 5. Judges (junction: Competition <-> Judge_List)
CREATE TABLE JUDGES (
    COMP_ID  VARCHAR(256),
    JUDGE_ID VARCHAR(256),
    PRIMARY KEY (COMP_ID, JUDGE_ID),
    FOREIGN KEY (COMP_ID)  REFERENCES COMPETITION(COMP_ID),
    FOREIGN KEY (JUDGE_ID) REFERENCES JUDGE_LIST(JUDGE_ID)
);

-- 6. Sponsorships (junction: Competition <-> Sponser)
CREATE TABLE SPONSERSHIPS (
    COMP_ID  VARCHAR(256),
    SPONS_ID VARCHAR(256),
    FOREIGN KEY (COMP_ID)  REFERENCES COMPETITION(COMP_ID),
    FOREIGN KEY (SPONS_ID) REFERENCES SPONSER(SPONS_ID)
);

-- 7. College
CREATE TABLE COLLEGE (
    COLLEGE_ID   VARCHAR(256) PRIMARY KEY,
    COLLEGE_NAME VARCHAR(256),
    LOCATION     VARCHAR(256)
);

-- 8. Participants
CREATE TABLE PARTICIPANTS (
    PARTICIPANT_ID VARCHAR(256) PRIMARY KEY,
    F_NAME         VARCHAR(256),
    L_NAME         VARCHAR(256),
    COLLEGE_ID     VARCHAR(256),
    ROLL_NUMBER    VARCHAR(256),
    EMAIL          VARCHAR(256),
    FOREIGN KEY (COLLEGE_ID) REFERENCES COLLEGE(COLLEGE_ID)
);

-- 9. Teams
CREATE TABLE TEAMS (
    TEAM_ID   VARCHAR(256) PRIMARY KEY,
    TEAM_NAME VARCHAR(256)
);

-- 10. Make_Team (junction: Teams <-> Participants)
CREATE TABLE MAKE_TEAM (
    TEAM_ID        VARCHAR(256),
    PARTICIPANT_ID VARCHAR(256),
    PRIMARY KEY (TEAM_ID, PARTICIPANT_ID),
    FOREIGN KEY (TEAM_ID)        REFERENCES TEAMS(TEAM_ID),
    FOREIGN KEY (PARTICIPANT_ID) REFERENCES PARTICIPANTS(PARTICIPANT_ID)
);

-- 11. Winners (junction: Teams <-> Competition)
CREATE TABLE WINNERS (
    TEAM_ID VARCHAR(256),
    COMP_ID VARCHAR(256),
    BOUNTY  NUMERIC,
    PRIMARY KEY (TEAM_ID, COMP_ID),
    FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID),
    FOREIGN KEY (COMP_ID) REFERENCES COMPETITION(COMP_ID)
);

-- 12. Registers (junction: Teams <-> Competition, with payment info)
CREATE TABLE REGISTERS (
    COMP_ID      VARCHAR(256),
    TEAM_ID      VARCHAR(256),
    PAYMENT_ID   VARCHAR(256),
    AMOUNT       NUMERIC,
    PAYMENT_DATE VARCHAR(256),
    PRIMARY KEY (TEAM_ID, COMP_ID),
    FOREIGN KEY (COMP_ID)  REFERENCES COMPETITION(COMP_ID),
    FOREIGN KEY (TEAM_ID)  REFERENCES TEAMS(TEAM_ID)
);


