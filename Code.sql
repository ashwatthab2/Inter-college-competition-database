-- Q1. Find all judges not assigned to any competition
SELECT JUDGE_LIST.*
FROM JUDGE_LIST
WHERE JUDGE_LIST.JUDGE_ID NOT IN (
    SELECT JUDGES.JUDGE_ID
    FROM JUDGES
);

-- Q2. Find winners of competition 'A000001'
SELECT TEAMS.TEAM_NAME, WINNERS.BOUNTY
FROM TEAMS
JOIN WINNERS ON TEAMS.TEAM_ID = WINNERS.TEAM_ID
WHERE WINNERS.COMP_ID = 'A000001';

-- Q3. Find all teams and their members registered for competition 'A000001'
SELECT TEAMS.*, PARTICIPANTS.*
FROM TEAMS
JOIN MAKE_TEAM   ON TEAMS.TEAM_ID            = MAKE_TEAM.TEAM_ID
JOIN PARTICIPANTS ON MAKE_TEAM.PARTICIPANT_ID = PARTICIPANTS.PARTICIPANT_ID
JOIN REGISTERS   ON TEAMS.TEAM_ID            = REGISTERS.TEAM_ID
WHERE REGISTERS.COMP_ID = 'A000001';

-- Q4. Find total number of participants from college 'C0001'
SELECT COUNT(*)
FROM PARTICIPANTS
WHERE PARTICIPANTS.COLLEGE_ID = 'C0001';

-- Q5. Find all teams with their participants and colleges for competition 'A000001'
SELECT TEAMS.TEAM_NAME, PARTICIPANTS.*, COLLEGE.COLLEGE_NAME
FROM TEAMS
JOIN MAKE_TEAM    ON TEAMS.TEAM_ID             = MAKE_TEAM.TEAM_ID
JOIN PARTICIPANTS ON MAKE_TEAM.PARTICIPANT_ID  = PARTICIPANTS.PARTICIPANT_ID
JOIN COLLEGE      ON PARTICIPANTS.COLLEGE_ID   = COLLEGE.COLLEGE_ID
JOIN REGISTERS    ON TEAMS.TEAM_ID             = REGISTERS.TEAM_ID
WHERE REGISTERS.COMP_ID = 'A000001';

-- Q6. Find competition names happening in Delhi
SELECT COMP_NAME
FROM COMPETITION
WHERE COMP_LOCATION = 'DELHI';

-- Q7. List teams that have not participated in any competition
SELECT TEAMS.*
FROM TEAMS
WHERE TEAMS.TEAM_ID NOT IN (
    SELECT MAKE_TEAM.TEAM_ID
    FROM MAKE_TEAM
);

-- Q8. Find names and emails of judges for competition 'A000001'
SELECT JF_NAME, JL_NAME, JUDGE_EMAIL
FROM JUDGE_LIST
INNER JOIN JUDGES ON JUDGE_LIST.JUDGE_ID = JUDGES.JUDGE_ID
WHERE JUDGES.COMP_ID = 'A000001';

-- Q9. Find total sponsorship received per competition
SELECT COMPETITION.COMP_NAME, SUM(SPONSER.SPONS_AMOUNT) AS TOTAL_SPONSORSHIP_RECEIVED
FROM COMPETITION
